// TestCreateNormalizesHeader：空 ID 生成、CreatedAt 填充、FormatVersion
// 填充；不兼容版本拒绝加载。
func TestCreateNormalizesHeader(t *testing.T) {
	store := NewMemoryStore()
	sess, err := store.Create(t.Context(), SessionHeader{})
	if err != nil {
		t.Fatal(err)
	}
	hdr := sess.Header()
	if hdr.SessionID == "" {
		t.Fatal("empty SessionID must be generated by store")
	}
	if hdr.CreatedAt.IsZero() {
		t.Fatal("zero CreatedAt must be filled by store")
	}
	if hdr.FormatVersion != FormatVersion {
		t.Fatalf("FormatVersion = %d, want %d", hdr.FormatVersion, FormatVersion)
	}
	_, err = store.Create(t.Context(), SessionHeader{FormatVersion: FormatVersion + 1})
	if !errors.Is(err, ErrFormatVersion) {
		t.Fatalf("err = %v, want ErrFormatVersion", err)
	}
}

// TestCreateRejectsSecondWriter：同 ID 已存在拒绝；并发 Create 同一 ID
// 恰好一个成功（内存单写者的确定性形态）。
func TestCreateRejectsSecondWriter(t *testing.T) {
	store := NewMemoryStore()
	if _, err := store.Create(t.Context(), SessionHeader{SessionID: "dup"}); err != nil {
		t.Fatal(err)
	}
	if _, err := store.Create(t.Context(), SessionHeader{SessionID: "dup"}); !errors.Is(err, ErrSessionExists) {
		t.Fatalf("err = %v, want ErrSessionExists", err)
	}
	const n = 8
	var wg sync.WaitGroup
	results := make([]error, n)
	for i := 0; i < n; i++ {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			_, results[i] = store.Create(t.Context(), SessionHeader{SessionID: "race"})
		}(i)
	}
	wg.Wait()
	ok := 0
	for _, err := range results {
		if err == nil {
			ok++
		} else if !errors.Is(err, ErrSessionExists) {
			t.Fatalf("unexpected error: %v", err)
		}
	}
	if ok != 1 {
		t.Fatalf("exactly one creator must win; got %d", ok)
	}
}

// TestOpenColdRecoverUnpaired：assistant 的 ToolCall 无 result → Open 补
// IsError result 且真实写回 log（Events 可查、Surface 合法）。
func TestOpenColdRecoverUnpaired(t *testing.T) {
	store := NewMemoryStore()
	sess, err := store.Create(t.Context(), SessionHeader{})
	if err != nil {
		t.Fatal(err)
	}
	id := sess.Header().SessionID
	ctx := t.Context()
	// 模拟崩溃现场：call 已记，result 未记。
	if _, err := sess.Append(ctx, assistantDraft(t, llm.Call(llm.ToolCall{ID: "c1"}))); err != nil {
		t.Fatal(err)
	}
	before, _ := sess.Events(ctx, 0)

	reopened, err := store.Open(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	events, err := reopened.Events(ctx, 0)
	if err != nil {
		t.Fatal(err)
	}
	if len(events) != len(before)+1 {
		t.Fatalf("events = %d, want %d（合成事件必须真实 Append 写回 log）", len(events), len(before)+1)
	}
	last := events[len(events)-1]
	if last.Type != EventToolResult {
		t.Fatalf("synthetic type = %s, want tool.result", last.Type)
	}
	var p ToolResultPayload
	if err := json.Unmarshal(last.Data, &p); err != nil || p.ToolCallID != "c1" || !p.IsError {
		t.Fatalf("synthetic payload = %+v (err=%v), want c1/IsError", p, err)
	}
	surface, err := reopened.Surface(ctx)
	if err != nil {
		t.Fatal(err)
	}
	// surface：assistant(带 call) + tool(interrupted)。
	if len(surface) != 2 || surface[1].Role != llm.RoleTool {
		t.Fatalf("surface = %v", surface)
	}
	res := surface[1].Parts[0].ToolResultValue
	if res == nil || res.ToolCallID != "c1" || !res.IsError || res.Content[0].Text != interruptedResultText {
		t.Fatalf("synthetic result = %+v", res)
	}
}

// TestOpenColdRecoverOpenTurnStep：未闭合 step/turn 按嵌套顺序补
// interrupted 结束事件（step 先于 turn）。
func TestOpenColdRecoverOpenTurnStep(t *testing.T) {
	store := NewMemoryStore()
	sess, err := store.Create(t.Context(), SessionHeader{})
	if err != nil {
		t.Fatal(err)
	}
	ctx := t.Context()
	for _, d := range []EventDraft{
		lifecycleDraft(t, EventTurnStarted, "t1", ""),
		lifecycleDraft(t, EventStepStarted, "s1", ""),
	} {
		if _, err := sess.Append(ctx, d); err != nil {
			t.Fatal(err)
		}
	}
	reopened, err := store.Open(ctx, sess.Header().SessionID)
	if err != nil {
		t.Fatal(err)
	}
	events, _ := reopened.Events(ctx, 0)
	if len(events) != 4 {
		t.Fatalf("events = %d, want 4", len(events))
	}
	if events[2].Type != EventStepEnded || events[3].Type != EventTurnEnded {
		t.Fatalf("synthetic order = %s, %s; want step.ended then turn.ended", events[2].Type, events[3].Type)
	}
	var stepEnded, turnEnded LifecyclePayload
	if err := json.Unmarshal(events[2].Data, &stepEnded); err != nil || stepEnded.Reason != ReasonInterrupted {
		t.Fatalf("step.ended = %+v (err=%v), want interrupted", stepEnded, err)
	}
	if stepEnded.ID != "s1" {
		t.Fatalf("step.ended.ID = %q, want %q（合成 ended 必须回带 started 的 ID）", stepEnded.ID, "s1")
	}
	if err := json.Unmarshal(events[3].Data, &turnEnded); err != nil || turnEnded.Reason != ReasonInterrupted {
		t.Fatalf("turn.ended = %+v (err=%v), want interrupted", turnEnded, err)
	}
	if turnEnded.ID != "t1" {
		t.Fatalf("turn.ended.ID = %q, want %q", turnEnded.ID, "t1")
	}
}

