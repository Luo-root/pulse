// TestConcurrentOpenSingleWriter：并发 Open 同一半截现场，恰好恢复一次；
// 第二写者得到 ErrWriterBusy（或等待窗口过后看到已闭合状态，幂等返回）。
// 两种结果都合法，但合成事件必须恰好一份。
func TestConcurrentOpenSingleWriter(t *testing.T) {
	store := NewMemoryStore()
	sess, _ := store.Create(t.Context(), SessionHeader{})
	ctx := t.Context()
	_, _ = sess.Append(ctx, assistantDraft(t, llm.Call(llm.ToolCall{ID: "c1"})))
	id := sess.Header().SessionID

	const n = 8
	var wg sync.WaitGroup
	errs := make([]error, n)
	for i := 0; i < n; i++ {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			_, errs[i] = store.Open(ctx, id)
		}(i)
	}
	wg.Wait()

	events, _ := sess.Events(ctx, 0)
	synthetic := 0
	for _, ev := range events {
		if ev.Type == EventToolResult {
			synthetic++
		}
	}
	if synthetic != 1 {
		t.Fatalf("synthetic tool.result = %d, want exactly 1; events=%d", synthetic, len(events))
	}
	for i, err := range errs {
		if err != nil && !errors.Is(err, ErrWriterBusy) {
			t.Fatalf("goroutine %d: unexpected error %v", i, err)
		}
	}
}

// TestListCursorPagination：CreatedAt 降序 + SessionID tiebreak；游标翻页
// 不重不漏；游标失效从头（安全行为）。
func TestListCursorPagination(t *testing.T) {
	store := NewMemoryStore(WithListPageSize(2))
	base := time.Now()
	ids := []string{"b", "a", "d", "c", "e"}
	for i, id := range ids {
		// 同一 CreatedAt 制造 tiebreak 场景。
		at := base.Add(time.Duration(i/2) * time.Minute)
		if _, err := store.Create(t.Context(), SessionHeader{SessionID: id, CreatedAt: at}); err != nil {
			t.Fatal(err)
		}
	}
	// 期望顺序：CreatedAt 降序，同刻 SessionID 升序（tiebreak）。
	// 2 分钟：e；1 分钟：c, d；0 分钟：a, b。
	want := []string{"e", "c", "d", "a", "b"}
	var got []string
	next := ""
	for page := 0; ; page++ {
		headers, n, err := store.List(t.Context(), SessionFilter{After: next})
		if err != nil {
			t.Fatal(err)
		}
		if len(headers) == 0 {
			break
		}
		for _, h := range headers {
			got = append(got, h.SessionID)
		}
		if n == "" {
			break
		}
		if page > 10 {
			t.Fatal("pagination did not terminate")
		}
		next = n
	}
	if len(got) != len(want) {
		t.Fatalf("listed %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("listed %v, want %v（CreatedAt 降序 + SessionID tiebreak）", got, want)
		}
	}
	// 游标失效 → ErrCursorStale（静默从头会重复返回，不做）。
	headers, _, err := store.List(t.Context(), SessionFilter{After: "gone"})
	if !errors.Is(err, ErrCursorStale) || headers != nil {
		t.Fatalf("stale cursor: err=%v, headers=%d; want ErrCursorStale", err, len(headers))
	}
}

